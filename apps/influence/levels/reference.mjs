import { createGraph } from '../engine/graph.mjs';

/** Visually transcribed from published Fig.1, p.27 (PDF p.2). */
export function figure1() {
  return createGraph({
    vertices: ['u', 'v', 'w', 'x', 'y', 'z'].map(id => ({ id, color: ['u', 'w'].includes(id) ? 'L' : 'R' })),
    arcs: [['u', 'w'], ['v', 'w'], ['x', 'v'], ['w', 'y'], ['w', 'z'], ['x', 'z']],
  });
}

export function segment(n, start = 1) {
  if (!Number.isSafeInteger(n) || n < 0 || !Number.isSafeInteger(start)) throw new RangeError('Invalid segment');
  const vertices = Array.from({ length: n }, (_, i) => ({ id: `${start + i}`, color: (start + i) % 2 === 0 ? 'L' : 'R' }));
  const arcs = [];
  for (let i = 0; i + 1 < n; i++) arcs.push(vertices[i].color === 'L' ? [vertices[i].id, vertices[i + 1].id] : [vertices[i + 1].id, vertices[i].id]);
  return createGraph({ vertices, arcs });
}

/** Alternating UNDIRECTED cycle, all arcs L -> R. Not a directed circuit. */
export function alternatingCycle(n) {
  if (!Number.isSafeInteger(n) || n < 4 || n % 2) throw new RangeError('Cycle needs even n >= 4');
  const g = segment(n);
  return createGraph({ vertices: g.vertices, arcs: [...g.arcs, [`${n}`, '1']] });
}

